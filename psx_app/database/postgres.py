SCHEMA_VERSION = '1.3.14'
_READY = False
_READY_LOCK = threading.Lock()
_SLOTS = threading.BoundedSemaphore(2)  # process-local ceiling, NOT a global pool
_LOCK_KEY = 731314
_NO_REVISION = {'indicator_cache','analysis_cache','psx_blob_parts','psx_runtime',
                'forecast_ledger','forecast_observations','learning_runs','reference_previews'}
_REPLACE_KEYS = {'indicator_cache':['symbol','trade_date','rule_version'],
                 'reference_previews':['token'],'company_reference':['list_name','symbol']}


def settings():
    uri = os.getenv('DATABASE_URL','').strip()
    try:
        p = urlsplit(uri)
        if p.scheme not in ('postgres','postgresql') or not p.hostname or not p.username or not p.path.strip('/'):
            raise ValueError()
        _ = p.port
    except Exception:
        raise RuntimeError('DATABASE_URL must be a valid PostgreSQL connection URI.') from None
    if os.getenv('PSX_PG_LOOPBACK_TEST')=='1' and p.hostname in ('127.0.0.1','localhost','::1'):
        return {'conninfo':uri,'sslmode':'disable','connect_timeout':5}
    cert = os.getenv('DATABASE_CA_CERT','').strip().replace('\\n','\n')
    if not (cert.startswith('-----BEGIN CERTIFICATE-----') and cert.endswith('-----END CERTIFICATE-----')):
        raise RuntimeError('DATABASE_CA_CERT must contain the complete PEM CA certificate.')
    cert += '\n'
    target = Path(tempfile.gettempdir())/('psx-ca-'+hashlib.sha256(cert.encode()).hexdigest()[:16]+'.pem')
    if not target.exists():
        fd, name = tempfile.mkstemp(prefix='psx-ca-',dir=tempfile.gettempdir())
        try:
            with os.fdopen(fd,'w') as f: f.write(cert)
            os.replace(name,target)
        finally:
            if os.path.exists(name): os.unlink(name)
    return {'conninfo':uri,'sslmode':'verify-full','sslrootcert':str(target),'connect_timeout':5}


def _bind(sql):
    out, i, quote = [], 0, None
    while i<len(sql):
        ch=sql[i]
        if quote:
            out.append('%%' if ch=='%' else ch)
            if ch==quote:
                if i+1<len(sql) and sql[i+1]==quote: out.append(quote); i+=1
                else: quote=None
        elif ch in ('\'', '"'): quote=ch;out.append(ch)
        else: out.append('%s' if ch=='?' else '%%' if ch=='%' else ch)
        i+=1
    return ''.join(out)


def translate(sql):
    s=sql.strip().rstrip(';')
    if re.match(r"(?is)^SELECT name FROM sqlite_master WHERE type='table'$",s):
        return "SELECT tablename AS name FROM pg_catalog.pg_tables WHERE schemaname=current_schema()"
    s=re.sub(r"(?i)datetime\('now'\)","to_char(timezone('UTC',now()), 'YYYY-MM-DD\"T\"HH24:MI:SS.US')",s)
    if 'reference_previews' in s: s=re.sub(r'(?i)ORDER BY rowid','ORDER BY preview_order',s)
    replace=re.match(r'(?is)^INSERT OR REPLACE INTO (\w+)\s*\(([^)]+)\)',s)
    if replace:
        table=replace[1].lower()
        if table not in _REPLACE_KEYS: raise ValueError('Unsupported application upsert table')
        cols=[x.strip() for x in replace[2].split(',')];keys=_REPLACE_KEYS[table]
        s=re.sub(r'(?i)^INSERT OR REPLACE','INSERT',s)
        s+=' ON CONFLICT ('+','.join(keys)+') DO UPDATE SET '+','.join(x+'=excluded.'+x for x in cols if x not in keys)
    elif re.match(r'(?is)^INSERT OR IGNORE\b',s):
        s=re.sub(r'(?i)^INSERT OR IGNORE','INSERT',s)+' ON CONFLICT DO NOTHING'
    return s


def schema_sql():
    from psx_app.database.schema import DDL_STATEMENTS
    statements=[]
    for statement in re.sub(r'--[^\n]*','',DDL_STATEMENTS).split(';'):
        s=statement.strip()
        if not s or s.upper().startswith('PRAGMA'): continue
        s=re.sub(r'\bINTEGER PRIMARY KEY AUTOINCREMENT\b','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',s)
        s=re.sub(r'\bINTEGER\b','BIGINT',s);s=re.sub(r'\bREAL\b','DOUBLE PRECISION',s);s=re.sub(r'\bBLOB\b','BYTEA',s)
        if s.startswith('CREATE TABLE IF NOT EXISTS reference_previews'):
            s=s.replace('(token ','(preview_order BIGINT GENERATED ALWAYS AS IDENTITY, token ')
        statements.append(s)
    return statements


def _value(v):
    if isinstance(v,Decimal): return int(v) if v==v.to_integral_value() else float(v)
    if isinstance(v,memoryview): return bytes(v)
    return v


class Cursor:
    def __init__(self,raw,lastrowid=None):
        self.raw=raw;self.names=[c.name for c in (raw.description or ())]
        self.description=raw.description;self.rowcount=raw.rowcount;self.lastrowid=lastrowid
    def fetchone(self):
        r=self.raw.fetchone()
        return None if r is None else Row(tuple(_value(v) for v in r),self.names)
    def fetchall(self): return [Row(tuple(_value(v) for v in r),self.names) for r in self.raw.fetchall()]
    def __iter__(self):
        while (r:=self.fetchone()) is not None: yield r


class Connection:
    def __init__(self,raw):
        self.raw=raw;self.dirty=False;self.in_transaction=False;self.closed=False;self.serialized=False
    def _begin(self,serialize=False):
        if not self.in_transaction:
            self.raw.execute('BEGIN');self.in_transaction=True
        if serialize and not self.serialized:
            self.raw.execute('SELECT pg_advisory_xact_lock(%s)',(_LOCK_KEY,));self.serialized=True
    def execute(self,sql,parameters=()):
        s=sql.strip().rstrip(';')
        if re.fullmatch(r'(?i)BEGIN(?: IMMEDIATE)?',s):
            try:
                self._begin(serialize=True)
                return Cursor(self.raw.execute('SELECT 1 WHERE FALSE'))
            except Exception as exc: raise safe_failure(exc,'begin',uncertain=self.dirty) from None
        if s.upper().startswith('PRAGMA'): raise ValueError('SQLite PRAGMA is not supported on PostgreSQL')
        change=re.match(r'(?is)^(?:INSERT(?: OR \w+)? INTO|UPDATE|DELETE FROM)\s*(\w+)',s)
        table=change[1].lower() if change else None
        try:
            if change or re.match(r'(?i)^(CREATE|ALTER|DROP)\b',s):
                self._begin(serialize=bool(table and table not in _NO_REVISION))
                if table and table not in _NO_REVISION: self.dirty=True
            s=translate(s)
            returning=table=='source_files' and s.upper().startswith('INSERT') and 'RETURNING' not in s.upper()
            if returning: s+=' RETURNING id'
            raw=self.raw.execute(_bind(s),tuple(parameters)) if parameters else self.raw.execute(s)
            last=raw.fetchone()[0] if returning else None
            return Cursor(raw,last)
        except Exception as exc: raise safe_failure(exc,'query',uncertain=self.dirty) from None
    def executemany(self,sql,parameters):
        match=re.match(r'(?is)^(\s*INSERT\b.*?\bVALUES\s*)(\([^()]*\))(.*)$',sql.strip().rstrip(';'))
        batch=[];size=0
        def flush():
            if not batch: return
            if match: self.execute(match[1]+','.join([match[2]]*len(batch))+match[3],tuple(x for row in batch for x in row))
            else:
                for row in batch: self.execute(sql,row)
        for row in parameters:
            n=sum(len(str(x)) for x in row)
            if batch and (len(batch)*len(row)+len(row)>5000 or size+n>500_000): flush();batch=[];size=0
            batch.append(row);size+=n
        flush()
    def commit(self):
        if not self.in_transaction: return
        try:
            if self.dirty: self.raw.execute("UPDATE psx_runtime SET value=%s WHERE key='revision'",(uuid.uuid4().hex,))
            self.raw.execute('COMMIT');self.in_transaction=False;self.dirty=False;self.serialized=False
        except Exception as exc: raise safe_failure(exc,'commit',uncertain=True) from None
    def rollback(self):
        try:
            if self.in_transaction: self.raw.execute('ROLLBACK')
        except Exception as exc:
            raise safe_failure(exc,'rollback',uncertain=self.dirty) from None
        finally: self.in_transaction=False;self.dirty=False;self.serialized=False
    def close(self):
        if not self.closed:
            try: self.raw.close()
            finally: self.closed=True;_SLOTS.release()
    def __enter__(self): return self
    def __exit__(self,kind,value,tb):
        try:
            if kind: self.rollback()
            else: self.commit()
        finally: self.close()


def connect():
    if not _SLOTS.acquire(timeout=5): raise DatabaseUnavailable('CONNECTION_CAPACITY','connect')
    raw=None
    try:
        import psycopg
        raw=psycopg.connect(**settings(),autocommit=True,application_name='psx-dashboard-1.3.14',
            options='-c client_encoding=UTF8 -c statement_timeout=90000 -c lock_timeout=15000 -c idle_in_transaction_session_timeout=120000',prepare_threshold=None)
        return Connection(raw)
    except Exception as exc:
        if raw is not None: raw.close()
        _SLOTS.release();raise safe_failure(exc,'connect') from None


def initialize():
    """Initialize a deliberately selected new PG database, never seed price data.
    Migration lock coordinates cold workers; no remote I/O during ASGI startup.
    """
    from psx_app.config import DEFAULT_SETTINGS,AUTHORIZED_ACCOUNTS
    with connect() as c:
        exists=c.raw.execute("SELECT to_regclass('public.psx_schema_version')").fetchone()[0]
        if exists:
            version=c.raw.execute('SELECT version FROM psx_schema_version WHERE singleton=1').fetchone()
            if version and version[0]==SCHEMA_VERSION: return
        with c.raw.transaction():
            c.raw.execute('SELECT pg_advisory_xact_lock(%s)',(_LOCK_KEY,))
            # Another cold worker may have completed initialization while we waited.
            if c.raw.execute("SELECT to_regclass('public.psx_schema_version')").fetchone()[0]:
                v=c.raw.execute('SELECT version FROM psx_schema_version WHERE singleton=1').fetchone()
                if v and v[0]==SCHEMA_VERSION: return
            for s in schema_sql(): c.raw.execute(s)
            c.raw.execute('CREATE TABLE IF NOT EXISTS psx_runtime(key TEXT PRIMARY KEY,value TEXT NOT NULL)')
            c.raw.execute("INSERT INTO psx_runtime VALUES ('revision',%s) ON CONFLICT DO NOTHING",(uuid.uuid4().hex,))
            c.raw.execute('CREATE TABLE IF NOT EXISTS psx_blob_parts(scope TEXT NOT NULL,part BIGINT NOT NULL,data BYTEA NOT NULL,updated_at BIGINT NOT NULL,PRIMARY KEY(scope,part))')
            c.raw.execute('CREATE INDEX IF NOT EXISTS idx_psx_blob_age ON psx_blob_parts(updated_at)')
            c.raw.execute('CREATE TABLE IF NOT EXISTS analysis_cache(cache_key TEXT PRIMARY KEY,revision TEXT NOT NULL,payload_json TEXT NOT NULL,updated_at TEXT NOT NULL)')
            c.raw.execute('CREATE TABLE IF NOT EXISTS psx_schema_version(singleton INTEGER PRIMARY KEY CHECK(singleton=1),version TEXT NOT NULL)')
            now=datetime.now(timezone.utc).isoformat()
            for acc in AUTHORIZED_ACCOUNTS:
                c.raw.execute("INSERT INTO accounts(account_id,terminal_id,label,currency,is_authorized,created_at) VALUES (%s,'THM00601',%s,'PKR',1,%s) ON CONFLICT DO NOTHING",(acc,'Account '+acc,now))
            for k,v in DEFAULT_SETTINGS.items():
                c.raw.execute('INSERT INTO app_settings(key,value_json,description,version,updated_at) VALUES (%s,%s,%s,1,%s) ON CONFLICT DO NOTHING',(k,json.dumps(v),'Setting: '+k,now))
            c.raw.execute('INSERT INTO psx_schema_version VALUES (1,%s) ON CONFLICT(singleton) DO UPDATE SET version=excluded.version',(SCHEMA_VERSION,))


def ensure_ready():
    global _READY
    if not _READY:
        with _READY_LOCK:
            if not _READY: initialize();_READY=True


def revision():
    with connect() as c: return c.execute("SELECT value FROM psx_runtime WHERE key='revision'").fetchone()[0]


def diagnostic():
    try:
        with connect() as c: c.execute('SELECT 1').fetchone()
        return {'code':'POSTGRESQL_READ_OK','note':'Connection/read verified; not a full integrity or write test.'}
    except Exception as exc: return {'code':safe_failure(exc,'postgres_read_diagnostic').code}
